export function evidenceText(value: string, language: "en" | "id"): string {
  if (language === "en") return value;
  const encodingWarning =
    ": source is not valid UTF-8; excluded from analysis and editing.";
  if (value.endsWith(encodingWarning))
    return (
      value.slice(0, -encodingWarning.length) +
      ": source bukan UTF-8; dikecualikan dari analisis dan pengeditan."
    );
  return evidenceId[value] || value;
}
